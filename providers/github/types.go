package github

// The wire structs below are the subsets of GitHub JSON the provider decodes.
// They deliberately omit any secret-bearing field: a field the struct does not
// name is dropped by the JSON decoder, so nothing sensitive in a response can
// reach a journal or a result record. (GitHub does not return a deploy key's
// private half or a webhook secret, and the tool never asks for them.)

// apiUser is the authenticated principal, from GET /user.
type apiUser struct {
	Login string `json:"login"`
	ID    int64  `json:"id"`
	Type  string `json:"type"`
}

// apiOrg is the organization, from GET /orgs/{org}.
type apiOrg struct {
	Login string `json:"login"`
	ID    int64  `json:"id"`
	Name  string `json:"name"`
}

// apiMembership is the authenticated user's membership in an org, from
// GET /user/memberships/orgs/{org}, and a member's org membership, from
// GET /orgs/{org}/memberships/{username}.
type apiMembership struct {
	State string `json:"state"`
	Role  string `json:"role"` // "admin" (owner) or "member"
	User  struct {
		Login string `json:"login"`
	} `json:"user"`
}

// apiRepo is a repository, from POST/GET /repos/{org}/{repo}.
type apiRepo struct {
	ID                  int64  `json:"id"`
	Name                string `json:"name"`
	Private             bool   `json:"private"`
	SecurityAndAnalysis struct {
		SecretScanning               apiFeatureStatus `json:"secret_scanning"`
		SecretScanningPushProtection apiFeatureStatus `json:"secret_scanning_push_protection"`
	} `json:"security_and_analysis"`
}

// apiFeatureStatus is one security feature's enablement.
type apiFeatureStatus struct {
	Status string `json:"status"` // "enabled" or "disabled"
}

// apiDeployKey is a repository deploy key, from POST/GET /repos/.../keys.
// Only the non-secret public half is ever present; the private half is
// generated by the tool and discarded before any call.
type apiDeployKey struct {
	ID    int64  `json:"id"`
	Title string `json:"title"`
	Key   string `json:"key"`
}

// apiHook is a repository webhook, from POST/GET /repos/.../hooks.
type apiHook struct {
	ID     int64  `json:"id"`
	Name   string `json:"name"`
	Config struct {
		URL string `json:"url"`
	} `json:"config"`
}

// apiInvitation is a pending repository invitation, from
// GET /repos/.../invitations.
type apiInvitation struct {
	ID      int64 `json:"id"`
	Invitee struct {
		Login string `json:"login"`
	} `json:"invitee"`
}

// apiBranchProtection is a branch's protection, from
// GET/PUT /repos/.../branches/{branch}/protection. The object name travels in
// required_status_checks.contexts, a real settable field, so the protection
// the tool created can be found again by its exact name.
type apiBranchProtection struct {
	RequiredStatusChecks struct {
		Contexts []string `json:"contexts"`
	} `json:"required_status_checks"`
}
